use std::fmt::Write;

use thetta_geometry::types::{GcodeConfig, Point3D, Tool, Toolpath, ToolpathMove};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum MotionMode {
    Rapid,
    Linear,
    ArcCw,
    ArcCcw,
}

#[derive(Debug, Clone, Copy, Default)]
struct ModalState {
    motion: Option<MotionMode>,
    feed: Option<i64>,
    pos: Option<Point3D>,
}

pub fn emit_gcode(
    toolpaths: &[Toolpath],
    tool: &Tool,
    config: &GcodeConfig,
    sheet_index: usize,
) -> String {
    emit_multi_op_gcode(&[], &[], toolpaths, None, None, tool, config, sheet_index)
}

pub fn emit_multi_op_gcode(
    drill_toolpaths: &[Toolpath],
    pocket_toolpaths: &[Toolpath],
    profile_toolpaths: &[Toolpath],
    drill_tool: Option<&Tool>,
    pocket_tool: Option<&Tool>,
    profile_tool: &Tool,
    config: &GcodeConfig,
    sheet_index: usize,
) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "%");
    let _ = writeln!(out, "(Sheet {} - Generated by Thetta)", sheet_index + 1);
    let _ = writeln!(out, "G21 (Metric)");
    let _ = writeln!(out, "G90 (Absolute positioning)");
    let _ = writeln!(out, "G17 (XY plane)");
    let _ = writeln!(
        out,
        "{} (Work coordinate system)",
        ascii_sanitize(&config.coordinate_system)
    );
    let _ = writeln!(out, "G0 Z{} (Safe Z)", fmt3(config.safe_z));

    let mut modal = ModalState {
        pos: Some(Point3D {
            x: 0.0,
            y: 0.0,
            z: config.safe_z,
        }),
        ..ModalState::default()
    };

    let groups: [(&str, &[Toolpath], Option<&Tool>); 3] = [
        ("Drill", drill_toolpaths, drill_tool),
        ("Pocket", pocket_toolpaths, pocket_tool),
        ("Profile", profile_toolpaths, Some(profile_tool)),
    ];

    let mut last_tool_number: Option<u32> = None;
    let mut last_rpm: Option<u32> = None;
    for (name, paths, tool_opt) in groups {
        if paths.is_empty() {
            continue;
        }
        let Some(tool) = tool_opt else {
            continue;
        };

        if last_tool_number != Some(tool.number) {
            if last_tool_number.is_some() {
                let _ = writeln!(out, "M5 (Spindle off)");
            }
            let _ = writeln!(out, "T{} M6 (Tool change)", tool.number);
            let _ = writeln!(
                out,
                "(Tool: T{} {} {:.3}mm)",
                tool.number,
                ascii_sanitize(&tool.name),
                tool.diameter
            );
            let _ = writeln!(out, "G43 H{} (Machine tool length offset)", tool.number);
            last_rpm = None;
            last_tool_number = Some(tool.number);
        }

        if last_rpm != Some(tool.spindle_speed) {
            let _ = writeln!(out, "S{} M3 (Spindle on CW)", tool.spindle_speed);
            last_rpm = Some(tool.spindle_speed);
        }
        let _ = writeln!(out);
        let _ = writeln!(out, "({name} Operations)");
        for (idx, path) in paths.iter().enumerate() {
            let _ = writeln!(out, "({name} Path {})", idx + 1);
            for mv in &path.moves {
                emit_move(&mut out, &mut modal, mv, config.cut_depth);
            }
        }
    }

    let _ = writeln!(out);
    let _ = writeln!(out, "M5 (Spindle off)");
    let _ = writeln!(out, "G0 Z{} (Retract to safe Z)", fmt3(config.safe_z));
    let _ = writeln!(out, "G0 X0.000 Y0.000 (Return to origin)");
    let _ = writeln!(out, "M2 (Program end)");
    let _ = writeln!(out, "%");

    out
}

fn emit_move(out: &mut String, modal: &mut ModalState, mv: &ToolpathMove, cut_depth: f64) {
    match mv {
        ToolpathMove::Rapid { to } => {
            if !is_finite_xyz(*to) {
                return;
            }
            write_motion_prefix(out, modal, MotionMode::Rapid);
            write_axes(out, modal.pos, *to, true);
            let _ = writeln!(out);
            modal.pos = Some(*to);
        }
        ToolpathMove::LinearCut { to, feed } => {
            if !is_finite_xyz(*to) || !feed.is_finite() {
                return;
            }
            let to = Point3D {
                z: to.z.min(0.0),
                ..*to
            };
            write_motion_prefix(out, modal, MotionMode::Linear);
            write_axes(out, modal.pos, to, true);
            write_feed(out, modal, *feed);
            let _ = writeln!(out);
            modal.pos = Some(to);
        }
        ToolpathMove::ArcCut {
            to,
            center,
            clockwise,
            feed,
        } => {
            if !is_finite_xyz(*to)
                || !center.x.is_finite()
                || !center.y.is_finite()
                || !feed.is_finite()
            {
                return;
            }
            let Some(from) = modal.pos else {
                return;
            };
            let to = Point3D {
                z: to.z.min(0.0),
                ..*to
            };
            let mode = if *clockwise {
                MotionMode::ArcCw
            } else {
                MotionMode::ArcCcw
            };
            write_motion_prefix(out, modal, mode);
            write_axes(out, modal.pos, to, true);
            let i = center.x - from.x;
            let j = center.y - from.y;
            if i.is_finite() && j.is_finite() {
                let _ = write!(out, " I{} J{}", fmt3(i), fmt3(j));
            }
            write_feed(out, modal, *feed);
            let _ = writeln!(out);
            modal.pos = Some(to);
        }
        ToolpathMove::TabLift { to, .. } => {
            if !is_finite_xyz(*to) {
                return;
            }
            let to = Point3D {
                z: to.z.min(0.0),
                ..*to
            };
            write_motion_prefix(out, modal, MotionMode::Linear);
            write_axes(out, modal.pos, to, true);
            let _ = writeln!(out);
            modal.pos = Some(to);
        }
        ToolpathMove::Retract { to_z } => {
            if !to_z.is_finite() {
                return;
            }
            write_motion_prefix(out, modal, MotionMode::Rapid);
            let z = to_z.max(0.0);
            let _ = write!(out, " Z{}", fmt3(z));
            let _ = writeln!(out);
            if let Some(mut pos) = modal.pos {
                pos.z = z;
                modal.pos = Some(pos);
            }
        }
        ToolpathMove::Plunge { to_z, feed } => {
            if !to_z.is_finite() || !feed.is_finite() {
                return;
            }
            write_motion_prefix(out, modal, MotionMode::Linear);
            let z = to_z.min(0.0).max(-cut_depth);
            let _ = write!(out, " Z{}", fmt3(z));
            write_feed(out, modal, *feed);
            let _ = writeln!(out);
            if let Some(mut pos) = modal.pos {
                pos.z = z;
                modal.pos = Some(pos);
            }
        }
        ToolpathMove::DrillCycleStart {
            depth,
            peck_depth,
            retract_z,
            feed,
        } => {
            if !depth.is_finite()
                || !peck_depth.is_finite()
                || !retract_z.is_finite()
                || !feed.is_finite()
            {
                return;
            }
            let _ = writeln!(
                out,
                "G83 Z{} R{} Q{} F{}",
                fmt3(-depth.abs()),
                fmt3(retract_z.max(0.0)),
                fmt3(peck_depth.abs()),
                feed.round() as i64
            );
            modal.motion = None;
            modal.feed = Some(feed.round() as i64);
        }
        ToolpathMove::DrillHole { position } => {
            if !position.x.is_finite() || !position.y.is_finite() {
                return;
            }
            let _ = writeln!(out, "X{} Y{}", fmt3(position.x), fmt3(position.y));
            if let Some(mut pos) = modal.pos {
                pos.x = position.x;
                pos.y = position.y;
                modal.pos = Some(pos);
            }
        }
        ToolpathMove::DrillCycleEnd => {
            let _ = writeln!(out, "G80");
            modal.motion = None;
        }
        ToolpathMove::HelicalRamp {
            center,
            radius,
            start_z: _,
            end_z,
            clockwise,
            feed,
        } => {
            if !center.x.is_finite()
                || !center.y.is_finite()
                || !radius.is_finite()
                || !end_z.is_finite()
                || !feed.is_finite()
            {
                return;
            }
            let r = radius.abs();
            let end = Point3D {
                x: center.x + r,
                y: center.y,
                z: end_z.min(0.0),
            };
            let mode = if *clockwise {
                MotionMode::ArcCw
            } else {
                MotionMode::ArcCcw
            };
            write_motion_prefix(out, modal, mode);
            write_axes(out, modal.pos, end, true);
            let _ = write!(out, " I{} J0.000", fmt3(-r));
            write_feed(out, modal, *feed);
            let _ = writeln!(out);
            modal.pos = Some(end);
        }
    }
}

fn write_motion_prefix(out: &mut String, modal: &mut ModalState, mode: MotionMode) {
    if modal.motion != Some(mode) {
        let code = match mode {
            MotionMode::Rapid => "G0",
            MotionMode::Linear => "G1",
            MotionMode::ArcCw => "G2",
            MotionMode::ArcCcw => "G3",
        };
        let _ = write!(out, "{code}");
        modal.motion = Some(mode);
    }
}

fn write_axes(out: &mut String, from: Option<Point3D>, to: Point3D, always_xyz: bool) {
    let changed_x = from.is_none_or(|p| (p.x - to.x).abs() > 1e-9);
    let changed_y = from.is_none_or(|p| (p.y - to.y).abs() > 1e-9);
    let changed_z = from.is_none_or(|p| (p.z - to.z).abs() > 1e-9);

    if always_xyz || changed_x {
        let _ = write!(out, " X{}", fmt3(to.x));
    }
    if always_xyz || changed_y {
        let _ = write!(out, " Y{}", fmt3(to.y));
    }
    if always_xyz || changed_z {
        let _ = write!(out, " Z{}", fmt3(to.z));
    }
}

fn write_feed(out: &mut String, modal: &mut ModalState, feed: f64) {
    let f = feed.round() as i64;
    if modal.feed != Some(f) {
        let _ = write!(out, " F{f}");
        modal.feed = Some(f);
    }
}

fn is_finite_xyz(p: Point3D) -> bool {
    p.x.is_finite() && p.y.is_finite() && p.z.is_finite()
}

fn ascii_sanitize(input: &str) -> String {
    input
        .chars()
        .filter(|c| c.is_ascii_graphic() || c.is_ascii_whitespace())
        .collect()
}

fn fmt3(v: f64) -> String {
    format!("{v:.3}")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tool() -> Tool {
        Tool {
            number: 3,
            name: "Tool α 6mm".to_string(),
            diameter: 6.0,
            flute_count: 2,
            feed_rate: 1500.0,
            plunge_rate: 500.0,
            spindle_speed: 18000,
        }
    }

    fn cfg() -> GcodeConfig {
        GcodeConfig {
            safe_z: 5.0,
            cut_depth: 18.0,
            tool_number: Some(3),
            coordinate_system: "G54".to_string(),
        }
    }

    #[test]
    fn test_preamble_and_postamble_format() {
        let g = emit_gcode(&[], &tool(), &cfg(), 0);
        assert!(g.contains("%\n(Sheet 1 - Generated by Thetta)"));
        assert!(g.contains("G21 (Metric)"));
        assert!(g.contains("G90 (Absolute positioning)"));
        assert!(g.contains("G17 (XY plane)"));
        assert!(g.contains("M5 (Spindle off)"));
        assert!(g.contains("M2 (Program end)"));
    }

    #[test]
    fn test_coordinate_precision_and_feed_format() {
        let path = Toolpath {
            moves: vec![
                ToolpathMove::Rapid {
                    to: Point3D {
                        x: 1.0 / 3.0,
                        y: 2.0 / 3.0,
                        z: 5.0,
                    },
                },
                ToolpathMove::LinearCut {
                    to: Point3D {
                        x: 10.0,
                        y: 20.0,
                        z: -18.0,
                    },
                    feed: 1500.0,
                },
            ],
            config: cfg(),
        };
        let g = emit_gcode(&[path], &tool(), &cfg(), 0);
        assert!(g.contains("X0.333"));
        assert!(g.contains("Y0.667"));
        assert!(g.contains("F1500"));
    }

    #[test]
    fn test_modal_gcode_linear() {
        let path = Toolpath {
            moves: vec![
                ToolpathMove::LinearCut {
                    to: Point3D {
                        x: 1.0,
                        y: 1.0,
                        z: -1.0,
                    },
                    feed: 1000.0,
                },
                ToolpathMove::LinearCut {
                    to: Point3D {
                        x: 2.0,
                        y: 1.0,
                        z: -1.0,
                    },
                    feed: 1000.0,
                },
            ],
            config: cfg(),
        };
        let g = emit_gcode(&[path], &tool(), &cfg(), 0);
        let piece = g.split("(Profile Operations)").nth(1).unwrap_or("");
        assert_eq!(piece.matches("G1").count(), 1);
    }

    #[test]
    fn test_no_nan_or_inf() {
        let path = Toolpath {
            moves: vec![ToolpathMove::Rapid {
                to: Point3D {
                    x: 0.0,
                    y: 0.0,
                    z: 5.0,
                },
            }],
            config: cfg(),
        };
        let g = emit_gcode(&[path], &tool(), &cfg(), 0);
        assert!(!g.contains("NaN"));
        assert!(!g.contains("Inf"));
    }

    #[test]
    fn test_drill_cycle_lines() {
        let path = Toolpath {
            moves: vec![
                ToolpathMove::DrillCycleStart {
                    depth: 12.0,
                    peck_depth: 3.0,
                    retract_z: 5.0,
                    feed: 250.0,
                },
                ToolpathMove::DrillHole {
                    position: thetta_geometry::types::Point2D { x: 1.0, y: 2.0 },
                },
                ToolpathMove::DrillCycleEnd,
            ],
            config: cfg(),
        };
        let g = emit_gcode(&[path], &tool(), &cfg(), 0);
        assert!(g.contains("G83 Z-12.000 R5.000 Q3.000 F250"));
        assert!(g.contains("X1.000 Y2.000"));
        assert!(g.contains("G80"));
    }

    #[test]
    fn test_helical_ramp_line() {
        let path = Toolpath {
            moves: vec![
                ToolpathMove::Rapid {
                    to: Point3D {
                        x: 5.0,
                        y: 0.0,
                        z: 5.0,
                    },
                },
                ToolpathMove::HelicalRamp {
                    center: thetta_geometry::types::Point2D { x: 0.0, y: 0.0 },
                    radius: 5.0,
                    start_z: 0.0,
                    end_z: -6.0,
                    clockwise: true,
                    feed: 300.0,
                },
            ],
            config: cfg(),
        };
        let g = emit_gcode(&[path], &tool(), &cfg(), 0);
        assert!(g.contains("G2 X5.000 Y0.000 Z-6.000 I-5.000 J0.000 F300"));
    }

    #[test]
    fn same_tool_optimization_skips_redundant_change() {
        let drill = Toolpath {
            moves: vec![ToolpathMove::DrillCycleStart {
                depth: 2.0,
                peck_depth: 1.0,
                retract_z: 5.0,
                feed: 100.0,
            }],
            config: cfg(),
        };
        let pocket = Toolpath {
            moves: vec![ToolpathMove::Rapid {
                to: Point3D {
                    x: 0.0,
                    y: 0.0,
                    z: 5.0,
                },
            }],
            config: cfg(),
        };
        let g = emit_multi_op_gcode(
            &[drill],
            &[pocket],
            &[],
            Some(&tool()),
            Some(&tool()),
            &tool(),
            &cfg(),
            0,
        );
        assert_eq!(g.matches("M6").count(), 1);
    }
    #[test]
    fn same_tool_different_operations_update_rpm() {
        let mut a = tool();
        let mut b = a.clone();
        a.spindle_speed = 18000;
        b.spindle_speed = 12000;
        let path = Toolpath {
            config: cfg(),
            moves: vec![ToolpathMove::Rapid {
                to: Point3D {
                    x: 1.,
                    y: 1.,
                    z: 5.,
                },
            }],
        };
        let code = emit_multi_op_gcode(
            &[],
            std::slice::from_ref(&path),
            std::slice::from_ref(&path),
            None,
            Some(&a),
            &b,
            &cfg(),
            0,
        );
        assert_eq!(code.matches(" M6 ").count(), 1);
        assert!(code.contains("G43 H3"));
        assert!(code.contains("S18000 M3"));
        assert!(code.contains("S12000 M3"));
    }
}
